# 5. VALIDATION SCRIPT
val_script = """import json
import sys

def validate():
    manifest_path = 'manifest.jsonl'
    
    total = 0
    valid = 0
    empty = 0
    duplicates = 0
    unverified = 0
    hindi_texts = set()
    ho_texts = set()
    
    try:
        with open(manifest_path, 'r', encoding='utf-8') as f:
            for line in f:
                if not line.strip(): continue
                total += 1
                rec = json.loads(line)
                
                h_txt = rec.get('hindi_text', '').strip()
                o_txt = rec.get('ho_text', '').strip()
                
                if not h_txt or not o_txt:
                    empty += 1
                    continue
                    
                if not rec.get('human_verified', False) or not rec.get('ground_truth', False):
                    unverified += 1
                    continue
                    
                if h_txt in hindi_texts or o_txt in ho_texts:
                    duplicates += 1
                    continue
                    
                if h_txt == o_txt:
                    empty += 1 # Treating exact identity as invalid
                    continue
                    
                hindi_texts.add(h_txt)
                ho_texts.add(o_txt)
                valid += 1
    except FileNotFoundError:
        pass
        
    md = f\"\"\"# HO NMT 1 SEED DATA VALIDATION

## AUDIT SUMMARY
- **Total Records**: {total}
- **Valid Human-Verified Pairs**: {valid}
- **Empty / Missing Text**: {empty}
- **Unverified Records**: {unverified}
- **Duplicates (Hindi or Ho overlap)**: {duplicates}

## SPLIT PROPOSAL (WHEN 100 VALID PAIRS EXIST)
- **Train**: 70 pairs
- **Validation**: 15 pairs
- **Test (Isolated)**: 15 pairs
\"\"\"
    js = {
        "total_records": total,
        "valid_pairs": valid,
        "empty_records": empty,
        "unverified_records": unverified,
        "duplicates": duplicates
    }
    
    with open('../../HO_NMT_1_SEED_DATA_VALIDATION.md', 'w') as f: f.write(md)
    with open('../../HO_NMT_1_SEED_DATA_VALIDATION.json', 'w') as f: json.dump(js, f, indent=2)

if __name__ == '__main__':
    validate()
"""
with open(os.path.join(base_dir, "validate_seed.py"), "w", encoding="utf-8") as f:
    f.write(val_script)

