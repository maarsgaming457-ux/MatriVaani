import requests
import time

def test_trans(text, src, tgt):
    start = time.time()
    try:
        res = requests.post("http://127.0.0.1:8000/translate", json={
            "text": text,
            "source_lang": src,
            "target_lang": tgt
        })
        dur = time.time() - start
        print(f"{src}->{tgt}: {res.status_code} - {res.json()} - Latency: {dur:.3f}s")
    except Exception as e:
        print(f"Error: {e}")

